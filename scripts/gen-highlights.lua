-- Generate queries/scheme/highlights.scm from data/builtins.json.
--   nvim -l scripts/gen-highlights.lua
-- Identifiers already highlighted by the upstream (nvim-treesitter) scheme
-- query are skipped so its more specific captures are kept.
local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
vim.opt.rtp:append(vim.fn.stdpath("data") .. "/site")

local data = vim.json.decode(table.concat(vim.fn.readfile(root .. "/data/builtins.json"), "\n"))

local upstream = {}
for _, file in ipairs(vim.api.nvim_get_runtime_file("queries/scheme/highlights.scm", true)) do
  if not file:find(root, 1, true) then
    for _, line in ipairs(vim.fn.readfile(file)) do
      if not line:match("^%s*;") then
        for s in line:gmatch('"([^"]+)"') do
          upstream[s] = true
        end
      end
    end
  end
end

local skip = { ["..."] = true, ["_"] = true, ["=>"] = true, ["else"] = true }
local keywords, procs = {}, {}
for _, s in ipairs(data.symbols) do
  local n = s.name
  if not upstream[n] and not skip[n] and not n:match("^&") then
    if s.kind == "syntax" then
      keywords[#keywords + 1] = n
    elseif s.kind == "procedure" then
      procs[#procs + 1] = n
    end
  end
end

local function any_of(capture, names)
  local out, line = {}, "   "
  for _, n in ipairs(names) do
    local q = ' "' .. n:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"'
    if #line + #q > 100 then
      out[#out + 1] = line
      line = "   "
    end
    line = line .. q
  end
  out[#out + 1] = line .. "))"
  return ("((symbol) %s\n  (#any-of? %s\n%s"):format(capture, capture, table.concat(out, "\n"))
end

local template = [[
; extends
; chez.nvim additions for Chez Scheme (%s).
; GENERATED by scripts/gen-highlights.lua -- edit that file instead.

; datum comments: #;(ignored form)
((sexp_comment) @comment
  (#set! priority 105))

; #eval blocks: the code is not coloured as a comment (it is highlighted
; through injections.scm); `#chez-eval-block!` narrows the range to the code
((block_comment) @chez.evalblock
  (#lua-match? @chez.evalblock "^#|%%s*#eval%%s")
  (#chez-eval-block! @chez.evalblock)
  (#set! priority 101))

; reader directives the grammar does not know: #!chezscheme #!fold-case ...
((ERROR) @keyword.directive
  (#lua-match? @keyword.directive "^#![%%a%%d%%-]+$"))

; special objects: #!eof #!bwp #!default #!base-rtd
((ERROR) @constant.builtin
  (#any-of? @constant.builtin "#!eof" "#!bwp" "#!default" "#!base-rtd"))

; #%%car #2%%car ($primitive references)
((ERROR) @function.builtin
  (#lua-match? @function.builtin "^#%%d*%%%%[^%%s()]+$"))

; condition types
((symbol) @type.builtin
  (#lua-match? @type.builtin "^&."))

; definitions
(list
  .
  (symbol) @_def
  .
  (list
    .
    (symbol) @function)
  (#any-of? @_def "define" "trace-define" "define-integrable" "define-inline"))

(list
  .
  (symbol) @_def
  .
  (symbol) @function.macro
  (#any-of? @_def "define-syntax" "trace-define-syntax" "define-top-level-syntax"
    "define-property" "extend-syntax"))

(list
  .
  (symbol) @_def
  .
  [
    (symbol) @type.definition
    (list
      .
      (symbol) @type.definition)
  ]
  (#any-of? @_def "define-record-type" "define-record" "define-structure"
    "define-condition-type" "define-enumeration" "define-ftype"))

; named let
(list
  .
  (symbol) @_let
  .
  (symbol) @function
  (#any-of? @_let "let" "trace-let"))

; library names: (library (foo bar) ...) (module name ...)
(list
  .
  (symbol) @_lib
  .
  (list
    (symbol) @module)
  (#eq? @_lib "library"))

(list
  .
  (symbol) @_mod
  .
  (symbol) @module
  (#eq? @_mod "module"))

; Chez Scheme syntactic forms
%s

; Chez Scheme procedures
%s
]]

local out = template:format(data.version, any_of("@keyword", keywords), any_of("@function.builtin", procs))
vim.fn.writefile(vim.split(out, "\n"), root .. "/queries/scheme/highlights.scm")
print(("wrote %d keywords, %d procedures"):format(#keywords, #procs))
